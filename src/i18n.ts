const DICTS: Record<string, Dict> = { es, en };
export const LANGUAGES = Object.keys(DICTS);
export const LANGUAGE_NAMES: Record<string, string> = { es: "Español", en: "English" };

let lang = "es";

export function setLang(l: string) {
  if (DICTS[l]) lang = l;
  document.documentElement.lang = lang;
}

export function getLang(): string {
  return lang;
}

/** Traduce una clave, con interpolación `{var}`. */
export function t(key: string, vars: Record<string, string | number> = {}): string {
  const raw = DICTS[lang][key] ?? DICTS.es[key] ?? key;
  return raw.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
}

/** Aplica traducciones a texto, `title` y `placeholder` marcados en el documento. */
export function applyI18n(root: ParentNode = document) {
  for (const el of root.querySelectorAll<HTMLElement>("[data-i18n]")) {
    el.textContent = t(el.dataset.i18n!);
  }
  for (const el of root.querySelectorAll<HTMLElement>("[data-i18n-title]")) {
    const label = t(el.dataset.i18nTitle!);
    el.title = label;
    el.setAttribute("aria-label", label);
  }
  for (const el of root.querySelectorAll<HTMLInputElement>("[data-i18n-placeholder]")) {
    el.placeholder = t(el.dataset.i18nPlaceholder!);
  }
}
